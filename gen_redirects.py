"""Generate _redirects: forced 301 from every extensionless page URL to its canonical .html URL.
Exact-path rules only, so /x.html never matches (no loop). Re-run after every build that adds pages."""
import glob, re
toml = open('netlify.toml', encoding='utf-8').read()
frm = set(re.findall(r'from\s*=\s*"([^"]+)"', toml))
rules, skip = [], []
for f in sorted(glob.glob('**/*.html', recursive=True)):
    f = f.replace(chr(92), '/')
    if f == '404.html' or f == 'index.html' or f.endswith('/index.html'): continue
    src, dst = '/' + f[:-5], '/' + f
    if src in frm: skip.append(src); continue
    rules.append((src, dst))
allfrom = frm | {r[0] for r in rules}
print(len(rules), 'rules; skipped (already in netlify.toml):', len(skip), '; dst that is also a from:', [r for r in rules if r[1] in allfrom][:3])
head = '# Extensionless page URLs -> canonical .html (Search Console "alternate page with proper canonical", 20 Nov 2026). Generated by gen_redirects.py\n'
open('_redirects', 'w', encoding='utf-8', newline='\n').write(head + ''.join('%s  %s  301!\n' % r for r in rules))
